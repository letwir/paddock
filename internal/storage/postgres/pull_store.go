package postgres

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/letwir/paddock/internal/governance/scheduler"
)

// PullStore calls only the narrow reservation function. Policy gates must already
// have completed before Reserve is entered; the function owns the atomic DB claim.
type PullStore struct{ pool *pgxpool.Pool }

func sameRequirements(a, b []scheduler.CapabilityRequirement) bool {
	if len(a) != len(b) {
		return false
	}
	values := make(map[string]string, len(a))
	for _, r := range a {
		if r.Name == "" || r.Value == "" {
			return false
		}
		if _, exists := values[r.Name]; exists {
			return false
		}
		values[r.Name] = r.Value
	}
	for _, r := range b {
		if values[r.Name] != r.Value {
			return false
		}
		delete(values, r.Name)
	}
	return len(values) == 0
}

func NewPullStore(pool *pgxpool.Pool) (*PullStore, error) {
	if pool == nil {
		return nil, errors.New("pull store: nil pool")
	}
	return &PullStore{pool}, nil
}

func (s *PullStore) Reserve(ctx context.Context, c scheduler.Candidate, w scheduler.Worker, permit scheduler.Permit, ttl time.Duration) (scheduler.Reservation, error) {
	var out scheduler.Reservation
	if s == nil || s.pool == nil {
		return out, errors.New("pull store: uninitialized pool")
	}
	if ctx == nil || strings.TrimSpace(c.WorkOrderID) == "" || strings.TrimSpace(w.ID) == "" || strings.TrimSpace(w.SessionID) == "" || ttl <= 0 {
		return out, errors.New("pull store: invalid request")
	}
	// PostgreSQL intervals have microsecond precision; reject sub-microsecond TTLs
	// rather than silently issuing an unexpectedly shorter lease.
	if ttl%time.Microsecond != 0 {
		return out, errors.New("pull store: invalid lease duration")
	}
	if !permit.Authorizes(c, w) {
		return out, scheduler.ErrRejected
	}
	// IDs are generated by the trusted Coordinator adapter; the DB atomically
	// binds these to the WorkOrder and its newly incremented epoch.
	raw := make([]byte, 16)
	if _, err := rand.Read(raw); err != nil {
		return out, errors.New("pull store: could not generate lease identity")
	}
	attemptID, slotID := "lease_"+hex.EncodeToString(raw), "slot_"+hex.EncodeToString(raw)
	// PostgreSQL's Pull function accepts JSON arrays, so preserve the semantic
	// empty set as [] rather than encoding a nil Go slice as JSON null.
	canonicalRequirements := c.Requirements
	if canonicalRequirements == nil {
		canonicalRequirements = []scheduler.CapabilityRequirement{}
	}
	canonicalEvidence := w.Evidence
	if canonicalEvidence == nil {
		canonicalEvidence = []scheduler.Evidence{}
	}
	requirements, err := json.Marshal(canonicalRequirements)
	if err != nil {
		return out, errors.New("pull store: could not encode requirements")
	}
	evidence, err := json.Marshal(canonicalEvidence)
	if err != nil {
		return out, errors.New("pull store: could not encode evidence")
	}
	err = s.pool.QueryRow(ctx, `SELECT attempt_id, slot_id, lease_epoch, expires_at FROM raw.issue_work_order_lease($1,$2,$3,$4,$5,$6::jsonb,$7::jsonb,$8::interval)`, c.WorkOrderID, w.ID, w.SessionID, attemptID, slotID, requirements, evidence, ttl).Scan(&out.AttemptID, &out.SlotID, &out.LeaseEpoch, &out.ExpiresAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return scheduler.Reservation{}, scheduler.ErrRejected
	}
	if err != nil {
		return scheduler.Reservation{}, errors.New("pull store: lease reservation failed")
	}
	out.SessionID = w.SessionID
	return out, nil
}

func validLeaseIdentity(id scheduler.LeaseIdentity) bool {
	return strings.TrimSpace(id.WorkOrderID) != "" && strings.TrimSpace(id.AttemptID) != "" && strings.TrimSpace(id.WorkerID) != "" && strings.TrimSpace(id.SessionID) != "" && id.Epoch > 0
}

func (s *PullStore) Heartbeat(ctx context.Context, id scheduler.LeaseIdentity, ttl time.Duration) (bool, error) {
	if s == nil || s.pool == nil || ctx == nil || !validLeaseIdentity(id) || ttl <= 0 || ttl%time.Microsecond != 0 {
		return false, errors.New("pull store: invalid heartbeat request")
	}
	var renewed bool
	if err := s.pool.QueryRow(ctx, `SELECT raw.heartbeat_work_order_lease($1,$2,$3,$4,$5,$6::interval)`, id.WorkOrderID, id.AttemptID, id.WorkerID, id.SessionID, id.Epoch, ttl).Scan(&renewed); err != nil {
		return false, errors.New("pull store: heartbeat failed")
	}
	return renewed, nil
}

func (s *PullStore) Reap(ctx context.Context, batch int) (int, error) {
	if s == nil || s.pool == nil || ctx == nil || batch <= 0 {
		return 0, errors.New("pull store: invalid reap request")
	}
	var reaped int
	if err := s.pool.QueryRow(ctx, `SELECT raw.reap_work_order_leases($1)`, batch).Scan(&reaped); err != nil {
		return 0, errors.New("pull store: lease reap failed")
	}
	return reaped, nil
}

func (s *PullStore) Complete(ctx context.Context, id scheduler.LeaseIdentity) (bool, error) {
	if s == nil || s.pool == nil || ctx == nil || !validLeaseIdentity(id) {
		return false, errors.New("pull store: invalid completion request")
	}
	var completed bool
	if err := s.pool.QueryRow(ctx, `SELECT raw.complete_work_order_lease($1,$2,$3,$4,$5)`, id.WorkOrderID, id.AttemptID, id.WorkerID, id.SessionID, id.Epoch).Scan(&completed); err != nil {
		return false, errors.New("pull store: lease completion failed")
	}
	return completed, nil
}
